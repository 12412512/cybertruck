import assert from 'node:assert/strict';
import {imagePoint,imageRect,parseRect,calibrationPoints,liveAge,cameraHealth,sourceName} from '../pi/robot/web/static/workbench-vision-state.js';
let count=0;
const check=fn=>{fn();count++;};
check(()=>assert.deepEqual(imagePoint(110,70,{left:10,top:20,width:200,height:100},[1280,720]),[640,360]));
check(()=>assert.deepEqual(imagePoint(-20,999,{left:10,top:20,width:200,height:100},[1280,720]),[0,719]));
check(()=>assert.deepEqual(imageRect([100,120],[20,30]),[20,30,100,120]));
check(()=>assert.throws(()=>imageRect([10,10],[10,50])));
check(()=>assert.deepEqual(parseRect('10，20，300，400',[640,480]),[10,20,300,400]));
for(const raw of ['','0,0,1','0,0,800,480','-1,0,640,480','1.5,0,640,480','0,0,NaN,20','10,10,5,5'])check(()=>assert.throws(()=>parseRect(raw,[640,480])));
check(()=>assert.deepEqual(calibrationPoints([]),[]));
check(()=>assert.throws(()=>calibrationPoints([{u:10,v:10,x_mm:'',y_mm:0}])));
const rows=[0,1,2,3,4].map((v,i)=>({u:v,v:v,x_mm:v,y_mm:v,check:i===4}));
check(()=>assert.equal(calibrationPoints(rows).length,5));
check(()=>assert.throws(()=>calibrationPoints(rows.map(p=>({...p,check:false})))));
check(()=>assert.equal(liveAge({domain:'camera_live',age_ms:100},1000,1100,40),240));
check(()=>assert.equal(liveAge({domain:'saved_sample'},1000,2000,40),null));
check(()=>assert.equal(liveAge({domain:'camera_live',age_ms:-1},1000,1100,40),Infinity));
check(()=>assert.equal(cameraHealth({cameras:{material:{available:false,reason:'断开'}}},'material').ok,false));
check(()=>assert.equal(cameraHealth({cameras:{material:{available:true,age_ms:25}}},'material').ok,true));
check(()=>assert.equal(sourceName({domain:'historical_replay'}),'旧样本回放'));
console.log(`${count} vision coordinate, freshness and input checks PASS`);
