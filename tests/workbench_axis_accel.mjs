import assert from 'node:assert/strict';
import {axisProfile,axisRateText} from '../pi/robot/web/static/workbench-axis-profile.js';
import {moveArgs} from '../pi/robot/web/static/workbench-remote-state.js';
import {sequenceRows,sameRows} from '../pi/robot/web/static/workbench-sequence.js';
const slow=axisProfile('reach',100,1,84),fast=axisProfile('reach',100,200,84);
assert.ok(slow.peakRpm<100);assert.equal(fast.peakRpm,100);
assert.ok(fast.seconds<slow.seconds);assert.ok(axisRateText('reach',100,1).includes('取得有效位置'));
assert.equal(axisProfile('reach',100,0,84).rateRpmS,null);
assert.equal(axisProfile('reach',100,200,0).seconds,0);
assert.throws(()=>axisProfile('reach',100,256,84));
const settings={manualTuning:true,gripMax:100,accel:160};
assert.equal(moveArgs('reach',84,100,false,settings).accel,160);
assert.ok(!('accel' in moveArgs('reach',84,100,false,{manualTuning:true})));
assert.throws(()=>moveArgs('reach',84,100,false,{...settings,accel:1.5}));
let rows=[{order:1,axis:'reach',target:84,speed:100,accel:160}];
const decoded=sequenceRows(rows,'ordered',{firmware:'GC-BASE-0.3.42'});
assert.equal(decoded[0].accel,160);
assert.ok(!sameRows(decoded,[{...decoded[0],accel:100}]));
assert.ok(sameRows([{axis:'reach',order:1,rpm:100}],[{axis:'reach',order:1,rpm:100,accel:1}]));
assert.throws(()=>sequenceRows([{...rows[0],accel:''}]));
console.log('轴曲线估算、旧版本默认、联调加速度保存/匹配与非法参数检查 PASS; 无设备调用');
